#!/bin/bash
# build_shader.sh - build the GFX12 vectorAdd compute blob.
#
# Requires an LLVM with the AMDGPU backend (clang, llvm-objcopy, llvm-readelf).
# On an Intel hackintosh: install the official LLVM release or Homebrew llvm,
# then run:
#   CLANG=.../bin/clang OBJCOPY=.../bin/llvm-objcopy \
#   READELF=.../bin/llvm-readelf ./build_shader.sh
#
# The old Metal path (metal/metallib) cannot be used for this kernel: Apple's
# AIR lowering passes [[thread_position_in_grid]] as an ordinary kernarg value,
# so every thread would read the same element index. The OpenCL path emits
# hardware workgroup/workitem ids (ttmp9/v0) and a standard kernarg segment.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
CLANG="${CLANG:-clang}"
OBJCOPY="${OBJCOPY:-llvm-objcopy}"
READELF="${READELF:-llvm-readelf}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$CLANG" -target amdgcn-amd-amdhsa -mcpu=gfx1201 -O2 -nogpulib -x cl \
    -c "$HERE/vectoradd.cl" -o "$TMP/vectoradd.o"

"$OBJCOPY" -O binary --only-section=.text "$TMP/vectoradd.o" "$TMP/vectoradd.bin"

# The kernel descriptor starts at .rodata offset 0:
#   0x30 COMPUTE_PGM_RSRC1, 0x34 COMPUTE_PGM_RSRC2.
"$READELF" -x .rodata "$TMP/vectoradd.o" > "$TMP/rodata.txt"

python3 - "$TMP/vectoradd.bin" "$TMP/rodata.txt" "$HERE/compiled/vectoradd_gfx12.h" <<'PY'
import re, struct, sys

bin_path, hex_path, out_path = sys.argv[1:4]
code = open(bin_path, 'rb').read()

hexwords = []
for line in open(hex_path):
    if not line.startswith('0x'):
        continue
    # Format: "0x00000030 00000fe0 84000000 08040000 00000000 ................"
    for tok in line.split()[1:5]:
        if len(tok) == 8 and all(c in '0123456789abcdefABCDEF' for c in tok):
            hexwords.append(int.from_bytes(bytes.fromhex(tok), 'little'))
if len(hexwords) < 14:
    sys.exit('could not parse .rodata from llvm-readelf output')
rsrc1 = hexwords[12]
rsrc2 = hexwords[13]

# Pad to a 256-byte multiple with s_code_end so a stray fetch ends the wave.
pad = (-len(code)) % 256
code += b'\x00\x00\x9f\xbf' * (pad // 4)
dwords = struct.unpack('<%dI' % (len(code) // 4), code)

lines = []
for i in range(0, len(dwords), 8):
    lines.append('    ' + ', '.join('0x%08xu' % x for x in dwords[i:i+8]) + ',')

header = '''// Generated by shaders/build_shader.sh from vectoradd.cl (gfx1201).
// Kernarg: { float* a; float* b; float* r; } at offsets 0/8/16.
// USER_SGPR = 2 (s[0:1] = kernarg pointer); thread ids come from hardware.
#ifndef VECTORADD_GFX12_H
#define VECTORADD_GFX12_H

static const unsigned int g_vectorAddShader[] = {
%s
};
static const unsigned int g_vectorAddShaderSize = %d;
static const unsigned int g_vectorAddRSRC1 = 0x%08Xu;
static const unsigned int g_vectorAddRSRC2 = 0x%08Xu;

#endif
''' % ('\n'.join(lines), len(code), rsrc1, rsrc2)

open(out_path, 'w').write(header)
print('wrote %s: %d bytes, RSRC1=0x%08X RSRC2=0x%08X'
      % (out_path, len(code), rsrc1, rsrc2))
PY
